const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const ts=require('typescript');
const read=p=>fs.readFileSync(path.join(__dirname,'..',p),'utf8');
const exportsObject={};
vm.runInNewContext(ts.transpileModule(read('src/utils/dayPlanImport.ts'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,{exports:exportsObject});
const {parseDayPlan,isProtectedStop,matchingStops}=exportsObject;
const plan=parseDayPlan('HOUNIGO-DAY/1 2030-02-01\n16:15 | Musée | notes\n09:30 | Train');
assert.equal(plan.rows[0].time,'09:30');assert.equal(plan.rows[1].notes,'notes');
assert.equal(matchingStops(plan.rows[1],[{titolo:'Musee'}]).length,1);
for(const raw of ['bad','HOUNIGO-DAY/1 2030-02-31\n09:00 | X','HOUNIGO-DAY/1 2030-02-01\n25:00 | X','HOUNIGO-DAY/1 2030-02-01\n09:00 | X\n10:00 | x']) assert.throws(()=>parseDayPlan(raw));
for(const field of ['bookingCode','qrCode','ticketUrl','linkedBookingId','linkedDocumentId','passeggiataId','completed']) assert.equal(isProtectedStop({[field]:true}),true);
assert.equal(isProtectedStop({attachments:[{}]}),true);
assert.equal(isProtectedStop({titolo:'Synthetic'}),false);
const storage=read('src/storage/storageService.ts');
const batch=storage.slice(storage.indexOf('async applyDayPlan('),storage.indexOf('async addTappa('));
assert.match(batch,/getAuthorizedLocalEditorRole/);assert.match(batch,/idbApplyDayStopBatch/);
assert.match(batch,/fingerprint\(active\) === fingerprint\(snapshot\)/);
assert.doesNotMatch(batch,/deleteTappa|idbDelete|deleteDoc|setDoc/);
assert.match(read('src/storage/indexedDB.ts'),/tx.oncomplete = \(\) => resolve\(\)/);
console.log('PASS: structured day validation, protected stops, preview and atomic local save');
