const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const ts=require('typescript');
const read=p=>fs.readFileSync(path.join(__dirname,'..',p),'utf8');
const load=(p,dependencies={})=>{
 const exports={};
 vm.runInNewContext(ts.transpileModule(read(p),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,{exports,require:id=>{assert.ok(id in dependencies,id);return dependencies[id];}});
 return exports;
};
const parser=load('src/utils/dayPlanImport.ts');
const planner=load('src/utils/typedDayPlan.ts',{'./dayPlanImport':parser});
const date='2030-06-01';
const plan=parser.parseDayPlan('HOUNIGO-DAY/2 '+date+'\n16:30 | tappa | Museo\n19:00 | metro | Metro verso Centro | Stazione → Centro | 19:30 | Cambio M2\n20:00 | ristorante | Cena Nuova | Cena');
assert.equal(plan.rows[1].from,'Stazione');
assert.equal(plan.rows[2].meal,'Cena');
assert.equal(parser.parseDayPlan('HOUNIGO-DAY/1 '+date+'\n20:00 | Cena Nuova').rows[0].category,'ristorante');
assert.throws(()=>parser.parseDayPlan('HOUNIGO-DAY/2 '+date+'\n19:00 | metro | Metro | Centro | 18:30'));
const stop=(id,titolo,extra={})=>({id,titolo,data:date,orario:'17:00',createdAt:100,updatedAt:100,sottocategoria:'Tappa',...extra});
const snap={tappe:[stop('a','Museo'),stop('b','Metro verso Centro'),stop('c','Cena Nuova',{nota:'Vecchia nota'})],ristoranti:[{id:'d',nome:'Cena precedente',sottocategoria:'Cena',data:date,orario:'19:30',budget:'35 €',updatedAt:100}],trasporti:[],alloggi:[],attivita:[],documenti:[],settings:[]};
let preview=planner.previewTypedDay(plan,snap);
assert.equal(preview.choices[0].action,'update');
assert.equal(preview.choices[1].action,'convert');
assert.equal(preview.choices[1].enabled,false);
assert.equal(preview.choices[2].enabled,false);
assert.ok(preview.retained.some(x=>x.includes('Cena precedente')));
let i=0;
const ops=planner.buildTypedDayOperations(plan,snap,preview,[0,1,2],'synthetic-user',200,()=> 'new-'+ ++i);
assert.equal(ops.filter(o=>o.action==='delete').length,2);
assert.ok(ops.filter(o=>o.action==='delete').every(o=>o.store==='tappe'));
assert.ok(ops.some(o=>o.store==='settings'&&o.record.value.explicitDeleteBy==='synthetic-user'));
assert.ok(ops.some(o=>o.store==='ristoranti'&&o.record.nome==='Nuova'&&o.record.notes==='Vecchia nota'));
assert.ok(ops.some(o=>o.store==='trasporti'&&o.record.type==='metro'&&o.record.arrivalTime==='19:30'));
assert.ok(!ops.some(o=>o.record.id==='d'));
const linked={...snap,documenti:[{id:'doc',linkedEntityId:'b'}]};
assert.equal(planner.previewTypedDay(plan,linked).choices[1].action,'skip');
assert.throws(()=>planner.buildTypedDayOperations(plan,linked,preview,[1],'user',200,()=> 'new'));
const protectedSnap={...snap,tappe:[...snap.tappe.slice(0,2),stop('c','Cena Nuova',{bookingCode:'synthetic'})]};
assert.equal(planner.previewTypedDay(plan,protectedSnap).choices[2].action,'skip');
const routing=read('src/services/routingService.ts');
assert.doesNotMatch(routing,/\? 18\.5 : 2\.4/);
assert.match(routing,/formattedDistance: 'Da verificare'/);
assert.match(routing,/manual\?\.route\?\.manualOverride/);
assert.match(routing,/\['~18\.5 km', '~2\.4 km'\]/);
console.log('PASS: typed import, opt-in replacement, no booking deletion, stale preview and unknown route protection');
